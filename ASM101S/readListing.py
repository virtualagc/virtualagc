import sys
import re

# Upon error, returns `None`.  Upon success, returns a dictionary whose keys
# are CSECT name, and whose values are themselves dictionaries representing the 
# control sections.  The dictionaries are structured as follows:
#    "pos"        Current halfword address.
#    "memory"     List of memory values, starting from byte address 0.  The
#                 values are integers in the range 0-255, or `None` at locations
#                 not used so far.
  
# While the numerical values in such lists are generally
# integers in the range 0-255, the value `None` may also appear for locations
# which are uninitialized.
chunkSize = 4096
def readListing(filename):
    
    sects = {}
    
    try:
        f = open(filename, "rt")
        source = f.readlines()
        f.close()
    except:
        return None
    
    # NOT EVERY LISTING STARTS IN COLUMN 1.  RUNLST's do, but the "as
    # received" listings in ~/workspace/PFS carry an ANSI carriage-control
    # character ahead of everything, so every field sits one column further
    # right and this reader -- which addresses its fields by column number --
    # would find no object code at all in them.
    #
    # The shift is not assumed.  Both alignments are tried and the one that
    # actually produces address lines wins, so a listing with some other
    # prefix would be handled too, and a file with no object code in it stays
    # at zero rather than being silently re-cut.
    def addressLines(offset):
        return sum(1 for line in source
                   if re.match(r"[0-9A-F]{5} ", line[offset:offset + 6]))
    shift = 0
    for candidate in range(1, 4):
        if addressLines(candidate) > addressLines(shift):
            shift = candidate
    if shift > 0:
        source = [line[shift:] for line in source]

    sect = None
    firstCSECT = None   # owns the literal pool; see below
    for line in source:
        if len(line) > 20 and line[20] == " ":
            front = line[:21]
        else:
            front = line[:30]
        back = line[36:36+71]
        col1 = back[:1]
        if col1 == "*":
            continue
        
        # Get the hex values related to the object code.
        frontFields = front.split()
        if len(frontFields) == 0 or len(frontFields[0]) != 5:
            continue
        try:
            address = int(frontFields[0], 16)
            address *= 2  # To get a byte address.
        except:
            continue
        values = []
        error = False
        for field in frontFields[1:]:
            if 0 != (len(field) & 1):
                error = True
                break
            for i in range(0, len(field), 2):
                try:
                    values.append(int(field[i:i+2], 16))
                except:
                    error = True
                    break
            if error:
                break
        if error:
            continue
        
        # Is this a line that affects the what control section we're in?
        backFields = back.split()
        if len(backFields) == 0:
            continue
        if len(backFields) > 0 and col1 == " ":
            name = None
            operation = backFields[0]
        elif len(backFields) > 1 and col1 != " ":
            name = backFields[0]
            operation = backFields[1]
        # THE LITERAL POOL BELONGS TO THE FIRST CONTROL SECTION, wherever it is
        # printed.  GC28-6514-8 page 23: the first control section "contains the
        # literals of the program, unless their positioning has been altered by
        # LTORG statements."  A listing prints the pool after everything else,
        # which in these modules is after the last DSECT and with no CSECT card
        # to end it -- so this reader was still inside the DSECT and filed the
        # pool's bytes there.  Nothing generates object code in a DSECT, so they
        # came back as missing:  FPMUPMTU's `=FS32'60E6'` at 002A6 was charged to
        # TFMTUSPL, and FPMCANCL's `=H'4'` to TFPDE.
        if operation[:1] == "=" or (name[:1] == "=" if name else False):
            if firstCSECT != None:
                sect = firstCSECT
        elif operation == "DSECT":
            sect = name
            continue
        elif operation == "CSECT" or (sect == None and len(values) > 0):
            if operation != "CSECT":
                name = ""
            if name not in sects:
                sects[name] = {
                    "pos": 0,
                    "memory": [None]*chunkSize
                    }
            sect = name
            if firstCSECT == None:
                firstCSECT = name
            #address *= 2
            #sects[sect]["pos"] = address
            #sects[sect]["memory"] = [None]*chunkSize
            continue
        
        # Now actually add the stuff to memory.
        for value in values:
            if sect not in sects:
                # A DSECT sets `sect` above without creating an entry here,
                # because a dummy section defines no storage of its own.  A
                # listing can still carry object code under one, and indexing
                # the missing entry was a KeyError that took the whole
                # comparison down before it began -- six OI301700 modules,
                # all of them naming the DSECT in the message and none of them
                # hinting that the listing reader was at fault.  Create it and
                # keep the bytes.
                sects[sect] = {
                    "pos": 0,
                    "memory": [None]*chunkSize
                    }
            while address >= len(sects[sect]["memory"]):
                sects[sect]["memory"] = sects[sect]["memory"] + ([None]*chunkSize)
            if sects[sect]["memory"][address] not in [None, value]:
                print("Memory overwritten: %s,%05X %02X->%02X" % \
                      (sect, address, sects[sect]["memory"][address], value))
            sects[sect]["memory"][address] = value
            address += 1
    
    for sect in sects:
        memory = sects[sect]["memory"]
        for n in range(len(memory)-1, -1, -1):
            if memory[n] == None:
                memory.pop()
            else:
                break
    return sects

