#!/usr/bin/env python3
"""Emit tables.c from model101tables.py.

The instruction tables are not written out by hand.  Several of them are built
by loops in the Python -- the `$`, `@` and `#` suffixed spellings, the
`argsSRSorRS` union, the per-operation parsing rules -- and transcribing the
RESULT of those loops by hand is exactly the sort of thing that goes wrong
silently and shows up as one wrong opcode in one module.  This imports the
module and writes what it actually holds.

Usage:  gentables.py /path/to/ASM101S tables.c
"""

import os
import sys

ASMDIR = sys.argv[1]
OUT = sys.argv[2]
sys.path.insert(0, ASMDIR)
os.chdir(ASMDIR)

import model101tables as T   # noqa: E402

# pseudoOps lives in ASM101S.py, which cannot be imported (it runs the
# assembler), so it is read out of the source text.
pseudoOps = {}
src = open("ASM101S.py").read()
start = src.index("pseudoOps = {")
end = src.index("}", start)
exec(src[start:end + 1], {}, pseudoOps)
pseudoOps = pseudoOps["pseudoOps"]

f = open(OUT, "w")
w = f.write

w('''/*
 * License:    This program is declared by its author, Ronald Burkey, to be the
 *             U.S. Public Domain, and may be freely used, modified, or
 *             distributed for any purpose whatever.
 * Filename:   tables.c
 * Purpose:    Instruction tables for the IBM AP-101S.
 * Contact:    info@sandroid.org
 *
 * WARNING: CAVEAT UTILITOR
 *
 *   Generated by tools/gentables.py from model101tables.py (and, for the
 *   pseudo-operation table, from ASM101S.py).  Several of these tables are
 *   built by loops in the Python -- the `$`, `@` and `#` suffixed spellings,
 *   the argsSRSorRS union, the per-operation parsing rules -- and this writes
 *   out what those loops actually produce.  Change the Python and regenerate;
 *   editing here will be overwritten.
 *
 *   The reasoning behind every value is in model101tables.py, which records
 *   for each group where the encoding was read off the original build and how
 *   far it is attested.  That commentary is not duplicated here because it
 *   belongs with the evidence, not with a generated table.
 */

#include "tables.h"

''')


def cstr(s):
    out = []
    for ch in s:
        if ch == '"':
            out.append('\\\\"')
        elif ch == '\\\\':
            out.append('\\\\\\\\')
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def emit_intmap(name, d):
    w("static const IntEntry %s_e[] = {\n" % name)
    for k, v in d.items():
        w('  { "%s", %d },\n' % (k, v))
    w("};\n")
    w("IntMap %s = { %s_e, sizeof (%s_e) / sizeof (IntEntry), NULL, 0 };\n\n"
      % (name, name, name))


def emit_strset(name, items):
    w("static const IntEntry %s_e[] = {\n" % name)
    for k in items:
        w('  { "%s", 0 },\n' % k)
    w("};\n")
    w("IntMap %s = { %s_e, sizeof (%s_e) / sizeof (IntEntry), NULL, 0 };\n\n"
      % (name, name, name))


def emit_strmap(name, d):
    w("static const StrEntry %s_e[] = {\n" % name)
    for k, v in d.items():
        w('  { "%s", "%s" },\n' % (k, v))
    w("};\n")
    w("StrMap %s = { %s_e, sizeof (%s_e) / sizeof (StrEntry) };\n\n"
      % (name, name, name))


for name in ("argsRR", "rrBranchAliases", "argsSRSandRS", "argsSRSonly",
             "shiftOperations", "branchAliases", "argsRSonly", "argsSRSorRS",
             "argsRI", "argsSI", "argsMSC", "argsBCE", "mscMemory",
             "mscImmediate", "mscImmediate11", "mscOpx", "bceShort2",
             "literalDatatypeAlignments", "instructionsWithoutOperands",
             "instructionsWithOperands", "knownInstructions"):
    emit_intmap(name, getattr(T, name))

emit_strset("bvcfAliases", T.bvcfAliases)
emit_strset("fpOperations", sorted(T.fpOperations))
emit_strset("fpOperationsSP", sorted(T.fpOperationsSP))
emit_strset("fpOperationsDP", sorted(T.fpOperationsDP))
emit_strset("mscImmediateZeroOnly", sorted(T.mscImmediateZeroOnly))
emit_strset("mscImmediateIndexable", sorted(T.mscImmediateIndexable))

emit_strmap("appropriateRules", T.appropriateRules)

# cnopFills:  the fill halfword, or "unknown" for the BCE's, whose padding has
# never been observed.
w("static const CnopEntry cnopFills_e[] = {\n")
for k, v in T.cnopFills.items():
    if v is None:
        w('  { "%s", 0, 0, 0 },\n' % k)
    else:
        w('  { "%s", 1, 0x%02X, 0x%02X },\n' % (k, v[0], v[1]))
w("};\n")
w("CnopMap cnopFills = { cnopFills_e, "
  "sizeof (cnopFills_e) / sizeof (CnopEntry) };\n\n")

# mscBranch: (index flag, condition code)
w("static const PairEntry mscBranch_e[] = {\n")
for k, (m, cc) in T.mscBranch.items():
    w('  { "%s", %d, %d },\n' % (k, m, cc))
w("};\n")
w("PairMap mscBranch = { mscBranch_e, "
  "sizeof (mscBranch_e) / sizeof (PairEntry) };\n\n")

# mscLong: (subop, mbit, field) where field is a number or "operand"
w("static const MscLongEntry mscLong_e[] = {\n")
for k, (subop, mbit, field) in T.mscLong.items():
    if field == "operand":
        w('  { "%s", %d, %d, 1, 0 },\n' % (k, subop, mbit))
    else:
        w('  { "%s", %d, %d, 0, %d },\n' % (k, subop, mbit, field))
w("};\n")
w("MscLongMap mscLong = { mscLong_e, "
  "sizeof (mscLong_e) / sizeof (MscLongEntry) };\n\n")

# bceShort1: (opcode, mbit or "index", kind)
w("static const BceShort1Entry bceShort1_e[] = {\n")
for k, (opcode, mbit, kind) in T.bceShort1.items():
    index = 1 if mbit == "index" else 0
    value = 0 if mbit == "index" else mbit
    w('  { "%s", 0x%X, %d, %d, %s },\n'
      % (k, opcode, index, value,
         "BCE_RELATIVE" if kind == "relative" else "BCE_IMMEDIATE"))
w("};\n")
w("BceShort1Map bceShort1 = { bceShort1_e, "
  "sizeof (bceShort1_e) / sizeof (BceShort1Entry) };\n\n")

# bceLong: (opcode, layout)
w("static const BceLongEntry bceLong_e[] = {\n")
layouts = {"ADDRESS": "BCE_ADDRESS", "DISPCOUNT": "BCE_DISPCOUNT",
           "IUACOMMAND": "BCE_IUACOMMAND", "PARAMETER": "BCE_PARAMETER"}
for k, (opcode, layout) in T.bceLong.items():
    w('  { "%s", 0x%02X, %s },\n' % (k, opcode, layouts[layout]))
w("};\n")
w("BceLongMap bceLong = { bceLong_e, "
  "sizeof (bceLong_e) / sizeof (BceLongEntry) };\n\n")

# impliedR1, from model101.py rather than model101tables.py.
impliedR1 = {
    "SSM": 0x0, "LM": 0x4, "STM": 0x0, "LPS": 0x5, "SVC": 0x1, "TS": 0x0,
    "SHW": 0x2, "TD": 0x0, "TH": 0x3, "ZH": 0x1,
}
for n in list(impliedR1):
    v = impliedR1[n]
    impliedR1[n + "@"] = v
    impliedR1[n + "@#"] = v
    impliedR1[n + "#"] = v
emit_intmap("impliedR1", impliedR1)

# The pseudo-operations, with the minimum and maximum number of comma-delimited
# operands each accepts; -1 for the maximum means "no limit".
w("static const PairEntry pseudoOps_e[] = {\n")
for k, (lo, hi) in pseudoOps.items():
    w('  { "%s", %d, %d },\n' % (k, lo, hi))
w("};\n")
w("PairMap pseudoOps = { pseudoOps_e, "
  "sizeof (pseudoOps_e) / sizeof (PairEntry) };\n")

f.close()
sys.stderr.write("tables.c written\n")
