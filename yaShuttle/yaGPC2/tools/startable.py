#!/usr/bin/env python3
"""Generate src/startable.h, the onboard star catalog for the star trackers.

    tools/startable.py <Star Tracker SOP .pdf> [<gpcN.mem.bin>] > src/startable.h

The star trackers (src/startrk.c) see the stars PASS expects to see: the 100
navigation stars of the orbiter star catalog, IDs 11-110.  Two sources:

  * FSSR STS 83-0014V2-34 (Star Tracker SOP), Table 5.2-1 "Orbiter Star
    Catalog (2005)": number, image-dissector (IDT) and solid-state (SSST)
    magnitudes, M50 unit vector, name.  Read with pdftotext -layout.  Only
    the rows between its heading and Table 5.2-2's (the 849 uplinkable stars)
    are taken.
  * Optionally a GPC memory image in OPS 2: CGYV_2_3_STAR_TABLE (IDs 1-60) and
    CGYV_2_8_STAR_TABLE (61-110), the vectors this tape's flight software
    actually holds, read with tools/pasvar.py.  When given, THOSE vectors are
    written (they are what PASS compares a sighting with) and the largest
    difference from the FSSR's is reported on stderr -- a check that the
    table and the tape are the same catalog.

The magnitude used for the threshold is the IDT column: the image-dissector
tracker is the one whose status bits mdmdev.c models.
"""
import math
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROW = re.compile(r'\s*(\d{2,3})\s+(-?\d\.\d)\s+(-?\d\.\d)\s+(-?\d\.\d+)\s+(-?\d\.\d+)'
                 r'\s+(-?\d\.\d+)\s+(.*\S)\s*$')


def fssr_rows(pdf):
    text = subprocess.run(["pdftotext", "-layout", pdf, "-"], capture_output=True,
                          text=True, check=True).stdout
    rows, inside = {}, False
    for line in text.splitlines():
        if "Table 5.2-1" in line:
            inside = True
            continue
        if "Table 5.2-2" in line:
            inside = False
            continue
        m = ROW.match(line) if inside else None
        if m:
            n = int(m.group(1))
            if 11 <= n <= 110:
                rows[n] = (float(m.group(2)), float(m.group(3)),
                           [float(m.group(i)) for i in (4, 5, 6)], m.group(7).strip())
    return rows


def memory_vectors(mem):
    out = {}
    for name, first in (("CGYV_2_3_STAR_TABLE", 1), ("CGYV_2_8_STAR_TABLE", 61)):
        text = subprocess.run([sys.executable, os.path.join(HERE, "pasvar.py"), "--config", "G2",
                               mem, name], capture_output=True, text=True, check=True).stdout
        k = first
        for m in re.finditer(r"I_STAR_SEL\s+@\w+\s+(?:\w{4}\s+){6}\(([^)]*)\)", text):
            out[k] = [float(x) for x in m.group(1).split(",")]
            k += 1
    return out


def main():
    if len(sys.argv) not in (2, 3):
        sys.exit(__doc__)
    rows = fssr_rows(sys.argv[1])
    missing = sorted(set(range(11, 111)) - set(rows))
    if missing:
        sys.exit("startable: Table 5.2-1 is missing star(s) %s" % missing)
    mem = memory_vectors(sys.argv[2]) if len(sys.argv) == 3 else {}
    if mem:
        worst, at = 0.0, None
        for n in range(11, 111):
            if n not in mem:
                sys.exit("startable: star %d is not in the memory image" % n)
            d = math.degrees(math.acos(max(-1.0, min(1.0, sum(a * b for a, b in zip(mem[n], rows[n][2]))))))
            if d > worst:
                worst, at = d, n
        print("startable: largest FSSR-to-memory difference %.6f deg (star %d)" % (worst, at),
              file=sys.stderr)
    print("/* THE ORBITER STAR CATALOG, IDs 11-110, for src/startrk.c.  GENERATED by")
    print(" * tools/startable.py from FSSR STS 83-0014V2-34 Table 5.2-1%s --" %
          (" and the tape's\n * CGYV_2_3/2_8_STAR_TABLE (the vectors)" if mem else ""))
    print(" * do not edit.  M50 unit vector, image-dissector magnitude, name. */")
    print("static const struct { int id; double u[3]; double mag; const char *name; }")
    print("STAR_TABLE[] = {")
    for n in range(11, 111):
        mag, _ssst, u, name = rows[n]
        if mem:
            u = mem[n]
        print('    { %3d, { %.9f, %.9f, %.9f }, %4.1f, "%s" },' % (n, u[0], u[1], u[2], mag, name))
    print("};")
    print("#define STAR_TABLE_N %d" % 100)


if __name__ == "__main__":
    main()
