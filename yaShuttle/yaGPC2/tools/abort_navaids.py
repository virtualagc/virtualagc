#!/usr/bin/env python3
"""YAGPC_NAVAIDS FOR THE FLOWN ABORT SITES: runway and MLS lines for the sites
in sts134-abort-iloads.json's #PCGN13R G3 cells, decoded as PASS decodes them.

    abort_navaids.py SLOT [SLOT ...] > OUT.txt        (runway slots, e.g. 7 8)
    abort_navaids.py --all > OUT.txt                  (every populated runway and every
                                                       MLS a runway points at, KSC from ours)

A runway's twin (ZZA30 / ZZA12, MRN20 / MRN02, EDW22 / EDW04 ...) is the SAME strip
approached from the other end: thresholds one runway length apart, azimuths 180 deg
apart.  The flown table gives an MLS to one direction only at ZZA, MRN and FMI (the
azimuth station stands at the far end, bearing back toward the approach, so it cannot
serve the reverse approach) and to both at EDW and EDT.

Why: landaids.c models only the beacons YAGPC_NAVAIDS lists, and
ksc-navaids.txt lists KSC alone, so a TAL to Zaragoza flew with the flown
table's MLS (CGNS_MLS_AREA_TABLE, reached through each runway's MSBLS_INDEX)
present in PASS and absent in the world.  Layouts: landing_sites.py.
"""
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RW_BASE, RW_STRIDE = 0x30322, 18
MLS_BASE, MLS_STRIDE = 0x30976, 28


def load():
    j = json.load(open(os.path.join(HERE, "sites", "sts134-abort-iloads.json")))
    mem = {}
    for c in j["cells"]:
        if c["config"] != "G3" or not c["name"].startswith("#PCGN13R"):
            continue
        a, h = int(c["addr"], 16), c["H"]
        for i in range(0, len(h), 4):
            mem[a + i // 4] = int(h[i:i + 4], 16)
    return mem


def rwid(w, b):
    return bytes(v for k in (1, 2, 3) for v in (w(b + k) >> 8, w(b + k) & 255)).decode("latin1").strip()


def all_sites(w, sf):
    print("# generated by tools/abort_navaids.py --all from sts134-abort-iloads.json (#PCGN13R G3 as PASS decodes it);")
    print("# KSC (runway/MLS slots 1-2) is ksc-navaids.txt's, the flown KSC entries being 'not ours' (see the spec's notes)")
    for line in open(os.path.join(HERE, "sites", "ksc-navaids.txt")):
        if not line.startswith("#"):
            sys.stdout.write(line)
    users = {}
    for slot in range(3, 91):
        b = RW_BASE + (slot - 1) * RW_STRIDE
        if not any(w(b + k) for k in range(4, 18)):
            continue
        print("runway %d %s %.17g %.17g %.17g %.17g" % (slot, rwid(w, b), sf(b + 4), sf(b + 6), sf(b + 12), sf(b + 8)))
        if w(b + 17):
            users.setdefault(w(b + 17), slot)
    for m, slot in sorted(users.items()):
        b = MLS_BASE + (m - 1) * MLS_STRIDE
        v = [sf(b + 2 * k) for k in range(8)]
        if abs(math.degrees(v[0]) - 28.59) < 0.1:       # a flown KSC entry
            continue
        print("mls %d %d %.17g %.17g %.17g %.17g %.17g %.17g %.17g %.17g" % (m, slot, *v))


def main():
    mem = load()
    w = lambda a: mem.get(a, 0)

    def sf(a):
        x = (w(a) << 16) | w(a + 1)
        if x == 0:
            return 0.0
        return (-1.0 if x & 0x80000000 else 1.0) * (x & 0xFFFFFF) / float(16 ** 6) * 16.0 ** (((x >> 24) & 0x7F) - 64)

    if sys.argv[1:] == ["--all"]:
        return all_sites(w, sf)
    print("# generated by tools/abort_navaids.py from sts134-abort-iloads.json (#PCGN13R G3 as PASS decodes it)")
    mls = []
    for slot in map(int, sys.argv[1:]):
        b = RW_BASE + (slot - 1) * RW_STRIDE
        rid = bytes(v for k in (1, 2, 3) for v in (w(b + k) >> 8, w(b + k) & 255)).decode("ascii").strip()
        lat, lon, az, alt, delh, msbls = sf(b + 4), sf(b + 6), sf(b + 8), sf(b + 12), sf(b + 14), w(b + 17)
        print("runway %d %s %.17g %.17g %.17g %.17g" % (slot, rid, lat, lon, alt, az))   # RUNWAY_ALT is already above the ellipsoid (927 ft at ZZA, the driver's ground)
        if msbls:
            mls.append((msbls, slot, az))
    for m, slot, az in mls:
        b = MLS_BASE + (m - 1) * MLS_STRIDE
        # CGN13R.hal:72-89: RAZ lat, lon, alt, bearing; EL lat, lon, alt, bearing (short floats)
        v = [sf(b + 2 * k) for k in range(8)]
        print("mls %d %d %.17g %.17g %.17g %.17g %.17g %.17g %.17g %.17g" % (m, slot, *v))


main()
