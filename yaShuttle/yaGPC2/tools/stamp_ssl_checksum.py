#!/usr/bin/env python3
"""Stamp SSLENGTH and SSLCKSUM into a mass-memory volume.

FCMCKSUM.asm declares both as DC H'0' and says who fills them in:

    FCMCKSUM WILL CONTAIN THE LENGTH OF THE SSL AND ITS ASSOCIATED
    CHECKSUM.  THE CHECKSUM WILL BE GENERATED BY THE MASS MEMORY BUILD
    PROGRAM.  ALSO, THIS DATA CSECT MUST BE THE LAST CSECT IN PHASE ONE.

Our reconstruction of that build writes each load block's own 2-halfword
checksum tail but not this one, so both reach the flight software as
zeros.  SSLCHECK (MLIB80) then sums with a count of zero, cannot match,
and takes its ERROR 22 path -- which deschedules it and returns to the
scheduler, so SSL70 never runs, FCMINSSL is never entered, and an
ITEM 1 EXEC loads nothing.  Nothing is ever asked of the mass memory,
which is exactly how the failure presents.

WHAT THE VALUES ARE

SSLCHECK's loop is

    LH   R3,SSLENGTH        R3 = count
    LA   R1,SSLSTART
    SHI  R1,1               R1 = SSLSTART-1
    AH   R4,0(X3,B1)        add the halfword at (SSLSTART-1)+R3
    BCT  R3,SSL30

so it sums SSLSTART .. SSLSTART+SSLENGTH-1, and the length is the span
from SSLSTART up to (not including) FCMCKSUM.  Excluding FCMCKSUM is what
keeps SSLCKSUM out of its own sum -- which is why that CSECT has to be
last.

The accumulation is `AH` into a register whose halfword operands sit in
the HIGH half, so carries fall off the top and the comparison `CH R4,
SSLCKSUM` reduces to (sum mod 2^16) == SSLCKSUM.  A plain 16-bit sum.

ORDER MATTERS: stamping these two changes the load block's content, so
its own checksum tail is recomputed afterwards.
"""
import argparse
import struct
import sys

HW_PER_BLOCK = 512


def load(path):
    raw = bytearray(open(path, "rb").read())
    if raw[:8] != b"MMUVOL01":
        sys.exit("%s is not an MMUVOL01 volume" % path)
    hw_per_block, entries, _ = struct.unpack(">III", raw[8:20])
    if hw_per_block != HW_PER_BLOCK:
        sys.exit("%s: unexpected block size" % path)
    dirs = [struct.unpack(">I", raw[32 + 4 * i:36 + 4 * i])[0]
            for i in range(entries)]
    return raw, dirs, 32 + 4 * entries


def block_index(track, file, subfile, block):
    return ((((file & 7) * 8 + (track & 7)) * 8 + (subfile & 7)) * 32
            + (block & 0x1f))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("volume")
    ap.add_argument("--phase-track", type=int, default=2)
    ap.add_argument("--phase-file", type=int, default=4)
    ap.add_argument("--phase-subfile", type=int, default=3)
    ap.add_argument("--phase-blocks", type=int, default=55)
    ap.add_argument("--lb-addr", type=lambda s: int(s, 16), default=0x6fbc,
                    help="memory address of the load block holding the SSL")
    ap.add_argument("--lb-len", type=int, default=994,
                    help="its length INCLUDING the 2-hw checksum tail")
    ap.add_argument("--sslstart", type=lambda s: int(s, 16), default=0x6fbc)
    ap.add_argument("--fcmcksum", type=lambda s: int(s, 16), default=0x7398,
                    help="address of the FCMCKSUM CSECT (the two slots)")
    ap.add_argument("--sslend", type=lambda s: int(s, 16), default=0x72e2,
                    help="end of the SSL; the link's own SSLEND equ.  The "
                         "summed span is SSLSTART..SSLEND-1, NOT up to "
                         "FCMCKSUM -- SSLEND sits inside FCMINSSL, so the "
                         "loader is shorter than its CSECT.")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()

    raw, dirs, data_off = load(a.volume)
    slot = {d: i for i, d in enumerate(dirs)}
    first = block_index(a.phase_track, a.phase_file, a.phase_subfile, 0)
    missing = [first + i for i in range(a.phase_blocks) if first + i not in slot]
    if missing:
        sys.exit("phase blocks missing from the volume: %s" % missing[:4])

    # Flatten the phase, remembering where each halfword lives in the file.
    pos = []
    for i in range(a.phase_blocks):
        base = data_off + slot[first + i] * HW_PER_BLOCK * 2
        pos.extend(base + 2 * h for h in range(HW_PER_BLOCK))
    def get(k): return (raw[pos[k]] << 8) | raw[pos[k] + 1]
    def put(k, v):
        raw[pos[k]] = (v >> 8) & 0xff
        raw[pos[k] + 1] = v & 0xff

    # The SSL load block sits at a fixed offset in the flattened phase; find
    # it by its own checksum tail rather than assuming a layout.
    content = a.lb_len - 2
    lb = None
    for k in range(0, len(pos) - a.lb_len):
        if (sum(get(k + i) for i in range(content)) & 0xffff) == get(k + content + 1):
            lb = k
            break
    if lb is None:
        sys.exit("could not find the SSL load block by its checksum tail")

    n = a.sslend - a.sslstart                 # SSLENGTH, per the SSLEND equ
    off_len = lb + (a.fcmcksum - a.lb_addr)   # SSLENGTH slot
    off_ck = off_len + 3                      # SSLCKSUM slot
    cks = sum(get(lb + (a.sslstart - a.lb_addr) + i) for i in range(n)) & 0xffff

    print("  SSL load block at phase offset %d (memory %#07x)" % (lb, a.lb_addr))
    print("  SSLENGTH  %#07x : %5d -> %5d" % (a.fcmcksum, get(off_len), n))
    print("  SSLCKSUM  %#07x : %#06x -> %#06x" % (a.fcmcksum + 3, get(off_ck), cks))
    if a.dry_run:
        print("  (dry run, nothing written)")
        return
    put(off_len, n)
    put(off_ck, cks)
    tail = sum(get(lb + i) for i in range(content)) & 0xffff
    print("  load-block checksum tail: %#06x -> %#06x" % (get(lb + content + 1), tail))
    put(lb + content, 0)
    put(lb + content + 1, tail)
    open(a.volume, "wb").write(bytes(raw))
    print("  wrote %s" % a.volume)


if __name__ == "__main__":
    main()
