#!/usr/bin/env python3
"""PASS's own air-data correction tables, for the simulated ADTAs.

    tools/adtatables.py [GYEADT.hal] > src/adtatables.h

The ADTA model (src/adtaair.c) must give PASS pressures that PASS's own
arithmetic (GYEADT.hal: the alpha cubic in the port ratio, the static- and
total-pressure corrections Cps and Cpt as quartics in alpha per Mach
segment, each with a gear-down increment) turns back into the vehicle's true
alpha, Mach and pressure.  So it carries those tables, taken here from the
source's own INITIAL lists -- no retyping.  Default source:
~/workspace/PFS/OI340600/APPLSRC/GYEADT.hal.
"""
import os
import re
import sys

SRC = os.path.expanduser("~/workspace/PFS/OI340600/APPLSRC/GYEADT.hal")
WANT = {"CGYS_MB_AOA": (11,), "CGYS_MB_PT": (15,), "CGYS_MB_SP": (18,),
        "CGYS_KS": (19, 5), "CGYS_KP": (16, 5), "CGYS_KA": (12, 4)}


def tables(path):
    text = "".join(l[:72] + "\n" for l in open(path, errors="replace")
                   if not l.startswith(("C", "D ")))
    out = {}
    for name, dims in WANT.items():
        m = re.search(r"DECLARE\s+%s\b[^;]*?INITIAL\s*\((.*?)\)\s*;" % name, text, re.S)
        if not m:
            raise SystemExit("adtatables: %s not found in %s" % (name, path))
        nums = [float(x.replace("E+", "e+").replace("E-", "e-").replace("E", "e"))
                for x in re.findall(r"-?\d*\.?\d+(?:E[-+]?\d+)?", m.group(1))]
        need = 1
        for d in dims:
            need *= d
        if len(nums) != need:
            raise SystemExit("adtatables: %s has %d values, wants %d" % (name, len(nums), need))
        out[name] = (dims, nums)
    return out


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else SRC
    t = tables(path)
    print("/* PASS's ADTA correction tables, GENERATED by tools/adtatables.py from")
    print(" * %s -- do not edit. */" % os.path.basename(path))
    for name, (dims, nums) in t.items():
        c = name.replace("CGYS_", "ADT_")
        if len(dims) == 1:
            print("static const double %s[%d] = { %s };" % (c, dims[0], ", ".join("%.8g" % x for x in nums)))
        else:
            rows = [nums[i * dims[1]:(i + 1) * dims[1]] for i in range(dims[0])]
            print("static const double %s[%d][%d] = {" % (c, dims[0], dims[1]))
            for r in rows:
                print("    { %s }," % ", ".join("%.8g" % x for x in r))
            print("};")
    return 0


if __name__ == "__main__":
    sys.exit(main())
