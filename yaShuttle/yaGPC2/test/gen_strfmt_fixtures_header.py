#!/usr/bin/env python3
"""Convert strfmt JSON fixtures into a C header for test_strfmt.c."""
import json
import sys


def c_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    data = json.load(open(sys.argv[1]))
    print("/* Auto-generated by gen_strfmt_fixtures_header.py — do not edit. */")
    print("#ifndef YAGPC_TEST_STRFMT_FIXTURES_H")
    print("#define YAGPC_TEST_STRFMT_FIXTURES_H")
    print()

    print("typedef struct { const char *s; const char *pad; int len; const char *expect; } PadFixture;")
    print(f"static const PadFixture LPAD_FIXTURES[{len(data['lpadCases'])}] = {{")
    for c in data['lpadCases']:
        print("    { %s, %s, %d, %s }," % (c_str(c['s']), c_str(c['pad']), c['len'], c_str(c['expect'])))
    print("};")
    print()

    print(f"static const PadFixture RPAD_FIXTURES[{len(data['rpadCases'])}] = {{")
    for c in data['rpadCases']:
        print("    { %s, %s, %d, %s }," % (c_str(c['s']), c_str(c['pad']), c['len'], c_str(c['expect'])))
    print("};")
    print()

    print("typedef struct { long long v; int len; const char *expect; } HexFixture;")
    print(f"static const HexFixture HEX_FIXTURES[{len(data['hexCases'])}] = {{")
    for c in data['hexCases']:
        print("    { %dLL, %d, %s }," % (c['v'], c['len'], c_str(c['expect'])))
    print("};")
    print()
    print("#endif")


if __name__ == "__main__":
    main()
