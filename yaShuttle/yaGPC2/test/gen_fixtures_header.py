#!/usr/bin/env python3
"""Convert PackedBits JSON fixtures (from gen_packedbits_fixtures.cjs) into a
C header of static test cases, for test_packedbits.c to check against."""
import json
import sys

FIELD_CHARS = "abcdefghijklmnopqrstuvwxyz_"


def c_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    data = json.load(open(sys.argv[1]))
    print("/* Auto-generated by gen_fixtures_header.py — do not edit. */")
    print("#ifndef YAGPC_TEST_PACKEDBITS_FIXTURES_H")
    print("#define YAGPC_TEST_PACKEDBITS_FIXTURES_H")
    print()
    print("typedef struct {")
    print("    const char *d;")
    print("    int len;")
    print("    const char *type;")
    print("    unsigned mask;")
    print("    unsigned maskedVal;")
    print("    char fieldChars[32];")
    print("    unsigned fieldMask[32];")
    print("    int fieldShift[32];")
    print("    int fieldBitlen[32];")
    print("    int fieldCount;")
    print("} PBFixture;")
    print()
    print(f"static const PBFixture PB_FIXTURES[{len(data)}] = {{")
    for entry in data:
        fields = entry["fields"]
        chars = sorted(fields.keys())
        fchars = "".join(chars)
        fmask = ", ".join(str(fields[c]["mask"]) for c in chars) or "0"
        fshift = ", ".join(str(fields[c]["shift"]) for c in chars) or "0"
        fbitlen = ", ".join(str(fields[c]["bitlen"]) for c in chars) or "0"
        print("    { %s, %d, %s, %uu, %uu, %s, {%s}, {%s}, {%s}, %d }," % (
            c_str(entry["d"]), entry["len"], c_str(entry["type"]),
            entry["mask"], entry["maskedVal"],
            c_str(fchars), fmask, fshift, fbitlen, len(chars)
        ))
    print("};")
    print()
    print("#endif")


if __name__ == "__main__":
    main()
