#include "srcmap.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define SRCMAP_STMT_FIELD_WIDTH 4
#define SRCMAP_TEXT_WIDTH 101
/* 0-based indices into a report line, per pass1.rpt's confirmed fixed
 * layout: "NNNN X|<101 chars>|<revision field>". This is the layout
 * WITHOUT the HALSFC `SRN` compile option; see SRCMAP_SRN_PREFIX_WIDTH
 * below for the other real layout, used when `SRN` is active. */
#define SRCMAP_COL1_INDEX 5
#define SRCMAP_BAR1_INDEX 6
#define SRCMAP_TEXT_START 7
#define SRCMAP_BAR2_INDEX (SRCMAP_TEXT_START + SRCMAP_TEXT_WIDTH)
#define SRCMAP_MIN_LEN (SRCMAP_BAR2_INDEX + 1)

/* When HALSFC is invoked with `SRN` in --parms, pass1.rpt prepends a
 * 6-digit Source Reference Number plus one separator space to the
 * FRONT of every source line in the STMT/SOURCE table -- confirmed
 * empirically (a real SRN-vs-non-SRN compile of the same source, byte-
 * offset diff = 7) and matching a direct user report of this exact
 * layout. This shifts every fixed column above by a constant 7 bytes;
 * SRN is a whole-compile option (not toggled per line), so the shift is
 * either 0 or SRCMAP_SRN_PREFIX_WIDTH for an entire pass1.rpt, never
 * mixed within one file. halmat_srcmap_load() below auto-detects which
 * by trying offset 0 first and falling back to this offset only if that
 * yields zero matched lines -- deliberately NOT based on matching the
 * header row's own "SRN STMT" vs "STMT" text, since a byte-offset
 * self-check against the real data lines is robust to header-wording
 * variations the way text matching wouldn't be. */
#define SRCMAP_SRN_PREFIX_WIDTH 7

static char *read_whole_file(const char *path, size_t *out_size) {
    FILE *f = fopen(path, "rb");
    if (!f) return NULL;
    if (fseek(f, 0, SEEK_END) != 0) { fclose(f); return NULL; }
    long size = ftell(f);
    if (size < 0 || fseek(f, 0, SEEK_SET) != 0) { fclose(f); return NULL; }
    char *buf = malloc((size_t)size + 1);
    if (!buf) { fclose(f); return NULL; }
    size_t nread = fread(buf, 1, (size_t)size, f);
    fclose(f);
    buf[nread] = '\0';
    *out_size = nread;
    return buf;
}

static bool parse_stmt_field(const char *line, int prefix, long *out) {
    char field[SRCMAP_STMT_FIELD_WIDTH + 1];
    memcpy(field, line + prefix, SRCMAP_STMT_FIELD_WIDTH);
    field[SRCMAP_STMT_FIELD_WIDTH] = '\0';

    bool has_digit = false;
    for (int i = 0; i < SRCMAP_STMT_FIELD_WIDTH; i++) {
        char c = field[i];
        if (c >= '0' && c <= '9') { has_digit = true; continue; }
        if (c == ' ') continue;
        return false; /* not a numeric statement field (e.g. blank, or garbage) */
    }
    if (!has_digit) return false;
    *out = strtol(field, NULL, 10);
    return true;
}

/* Scans `buf` (size `size`) for pass1.rpt data lines using a given
 * `prefix` byte offset (0, or SRCMAP_SRN_PREFIX_WIDTH -- see that
 * macro's own comment), appending every match to `*lines`/`*count`/
 * `*capacity` (each grown via realloc as needed, matching the original
 * single-pass loop's own allocation shape). Returns false only on
 * out-of-memory; a `prefix` that doesn't match this file's real layout
 * simply yields *count == 0 (every line fails the bar1/bar2 '|' check),
 * which the caller uses as its own auto-detection signal. */
static bool scan_lines(const char *buf, size_t size, int prefix,
                        halmat_srcmap_line_t **lines, size_t *count, size_t *capacity,
                        char *errbuf, size_t errbuf_size, const char *path) {
    size_t min_len = (size_t)prefix + SRCMAP_MIN_LEN;
    size_t bar1 = (size_t)prefix + SRCMAP_BAR1_INDEX;
    size_t bar2 = (size_t)prefix + SRCMAP_BAR2_INDEX;

    const char *line_start = buf;
    while (line_start < buf + size) {
        const char *nl = strchr(line_start, '\n');
        size_t line_len = nl ? (size_t)(nl - line_start) : strlen(line_start);
        /* Report lines are CR-free in practice, but strip a trailing \r
         * defensively (pass1.rpt is generated by a DOS-heritage toolchain
         * per this project's other companion files). */
        size_t trimmed_len = line_len;
        if (trimmed_len > 0 && line_start[trimmed_len - 1] == '\r') trimmed_len--;

        if (trimmed_len >= min_len &&
            line_start[bar1] == '|' &&
            line_start[bar2] == '|') {
            long stmt;
            if (parse_stmt_field(line_start, prefix, &stmt)) {
                if (*count >= *capacity) {
                    *capacity *= 2;
                    halmat_srcmap_line_t *grown = realloc(*lines, *capacity * sizeof(halmat_srcmap_line_t));
                    if (!grown) {
                        snprintf(errbuf, errbuf_size, "out of memory parsing '%s'", path);
                        for (size_t i = 0; i < *count; i++) free((*lines)[i].text);
                        free(*lines);
                        *lines = NULL;
                        return false;
                    }
                    *lines = grown;
                }
                /* The ENTIRE raw report line, verbatim (STMT field, the
                 * column-1 marker, both bars, the full source-text field
                 * with its own trailing blanks intact, and the trailing
                 * revision/scope field) -- not a reconstructed subset.
                 * Only the line terminator itself is excluded. */
                char *text = malloc(trimmed_len + 1);
                memcpy(text, line_start, trimmed_len);
                text[trimmed_len] = '\0';

                (*lines)[*count].stmt = stmt;
                (*lines)[*count].text = text;
                (*count)++;
            }
        }

        if (!nl) break;
        line_start = nl + 1;
    }
    return true;
}

bool halmat_srcmap_load(const char *path, halmat_srcmap_t *out, char *errbuf, size_t errbuf_size) {
    memset(out, 0, sizeof(*out));

    size_t size = 0;
    char *buf = read_whole_file(path, &size);
    if (!buf) {
        snprintf(errbuf, errbuf_size, "cannot read PASS1 report '%s'", path);
        return false;
    }

    size_t capacity = 256;
    halmat_srcmap_line_t *lines = malloc(capacity * sizeof(halmat_srcmap_line_t));
    if (!lines) {
        snprintf(errbuf, errbuf_size, "out of memory parsing '%s'", path);
        free(buf);
        return false;
    }
    size_t count = 0;

    /* Auto-detect the SRN-vs-plain layout (see SRCMAP_SRN_PREFIX_WIDTH's
     * own comment): try the far more common no-SRN offset first, and
     * only fall back to the SRN-shifted offset if that produced zero
     * data lines. A `count` of 0 either way just leaves the map empty,
     * the same graceful-degradation behavior this had before SRN
     * support existed. */
    if (!scan_lines(buf, size, 0, &lines, &count, &capacity, errbuf, errbuf_size, path)) {
        free(buf);
        return false;
    }
    if (count == 0) {
        if (!scan_lines(buf, size, SRCMAP_SRN_PREFIX_WIDTH, &lines, &count, &capacity, errbuf, errbuf_size, path)) {
            free(buf);
            return false;
        }
    }

    free(buf);
    out->lines = lines;
    out->count = count;
    return true;
}

void halmat_srcmap_free(halmat_srcmap_t *map) {
    for (size_t i = 0; i < map->count; i++) free(map->lines[i].text);
    free(map->lines);
    map->lines = NULL;
    map->count = 0;
}

const halmat_srcmap_line_t *halmat_srcmap_find(const halmat_srcmap_t *map, long stmt, size_t *out_count) {
    for (size_t i = 0; i < map->count; i++) {
        if (map->lines[i].stmt != stmt) continue;
        size_t n = 1;
        while (i + n < map->count && map->lines[i + n].stmt == stmt) n++;
        *out_count = n;
        return &map->lines[i];
    }
    return NULL;
}
